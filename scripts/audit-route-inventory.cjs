// Generates docs/audit/route-inventory.md: every API route, the HTTP methods
// it exports, and how a caller is authenticated and authorised.
//
//   node scripts/audit-route-inventory.cjs
//
// Classification is read from the source, so it stays honest as routes change:
//   • access      — which gate in proxy.ts the path goes through
//   • authorised  — the in-handler check, if any (permission / role / API key …)
//   • institution — whether the handler reads an institution id from the request
const fs = require('fs')
const path = require('path')

const ROOT = path.join(__dirname, '..')
const API = path.join(ROOT, 'app', 'api')
const OUT = path.join(ROOT, 'docs', 'audit', 'route-inventory.md')

// Mirrors publicApiRoutes / publicApiPatterns in proxy.ts.
const PUBLIC_PREFIXES = [
	'/api/auth', '/api/token', '/api/public', '/api/v1',
	'/api/examiner-portal', '/api/examiner/question-paper', '/api/cron',
]
const PUBLIC_PATTERNS = [/^\/api\/courses\/[^/]+\/syllabus-pdf\/?$/]

// Rules from lib/auth/api-policy.ts (enforced in proxy.ts), read from the source.
const { API_POLICY, findApiPolicyRule } = require(path.join(ROOT, 'lib', 'auth', 'api-policy.ts'))

// Rules derived from the calling screens (scripts/generate-api-policy.cjs).
const GENERATED_FILE = path.join(ROOT, 'lib', 'auth', 'api-policy.generated.ts')
const GENERATED = fs.existsSync(GENERATED_FILE)
	? [...fs.readFileSync(GENERATED_FILE, 'utf8').matchAll(/prefix: '([^']+)', exact: true,( methods: \['GET'\],)?/g)]
		.map((m) => ({ segments: m[1].split('/'), readsOnly: Boolean(m[2]) }))
	: []

function walk(dir, acc = []) {
	for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
		const full = path.join(dir, entry.name)
		if (entry.isDirectory()) walk(full, acc)
		else if (entry.name === 'route.ts') acc.push(full)
	}
	return acc
}

function classify(file) {
	const src = fs.readFileSync(file, 'utf8')
	const route = '/api/' + path.relative(API, path.dirname(file)).split(path.sep).join('/')

	const methods = new Set()
	for (const m of src.matchAll(/export\s+(?:async\s+)?function\s+(GET|POST|PUT|PATCH|DELETE)\b/g)) methods.add(m[1])
	for (const m of src.matchAll(/export\s+const\s+(GET|POST|PUT|PATCH|DELETE)\b/g)) methods.add(m[1])

	const isPublic =
		PUBLIC_PREFIXES.some((p) => route === p || route.startsWith(p + '/')) ||
		PUBLIC_PATTERNS.some((re) => re.test(route.replace(/\[[^\]]+\]/g, 'x')))

	const checks = []
	if (/requireUserPermission\(/.test(src)) checks.push('permission')
	if (/withAdminAuth\(/.test(src)) checks.push('admin role')
	if (/hasAnyCoeRole\(/.test(src)) checks.push('role')
	if (/getRequestUser\(|resolveCallerEmail\(|resolveVerifiedCaller\(/.test(src)) checks.push('session')
	if (/withExternalAuth\(|withApiAuth\(/.test(src)) checks.push('API key')
	if (/requireExaminer\(|requireAssignment\(/.test(src)) checks.push('examiner session')
	if (/CRON_SECRET/.test(src)) checks.push('cron secret')
	const concrete = route.replace(/\[[^\]]+\]/g, 'x')
	const forReads = findApiPolicyRule(concrete, 'GET', API_POLICY)
	const forWrites = findApiPolicyRule(concrete, 'POST', API_POLICY)
	if (!isPublic && forReads) checks.push('permission policy')
	else if (!isPublic && forWrites) checks.push('permission policy (writes)')
	const shape = route.split('/').map((seg) => (seg.startsWith('[') ? '*' : seg))
	const generated = GENERATED.find((g) => g.segments.length === shape.length && g.segments.every((seg, i) => seg === shape[i]))
	if (generated && !isPublic) checks.push(generated.readsOnly ? 'permission policy (screens, reads)' : 'permission policy (screens)')

	const serviceRole = /getSupabaseServer\(|SUPABASE_SERVICE_ROLE_KEY/.test(src)
	const institution = /institutions?_id|institution_code|institutionId/.test(src)
	const writes = [...methods].some((m) => m !== 'GET')

	return { route, methods: [...methods].sort(), isPublic, checks, serviceRole, institution, writes }
}

const routes = walk(API).map(classify).sort((a, b) => a.route.localeCompare(b.route))

const access = (r) => (r.isPublic ? 'public prefix' : 'COE session (proxy)')
const authorised = (r) => (r.checks.length ? r.checks.join(' + ') : '—')

const protectedRoutes = routes.filter((r) => !r.isPublic)
const noPermission = protectedRoutes.filter((r) => !r.checks.some((c) => ['permission', 'admin role', 'role'].includes(c) || c.startsWith('permission policy')))
const publicNoCheck = routes.filter((r) => r.isPublic && r.checks.length === 0)

const lines = []
lines.push('# API route inventory')
lines.push('')
lines.push('Generated by `node scripts/audit-route-inventory.cjs` — do not edit by hand.')
lines.push('')
lines.push('| | Count |')
lines.push('|---|---:|')
lines.push(`| API routes | ${routes.length} |`)
lines.push(`| Behind the COE session check in \`proxy.ts\` | ${protectedRoutes.length} |`)
lines.push(`| … of which also check a permission or role in the handler | ${protectedRoutes.length - noPermission.length} |`)
lines.push(`| … of which rely on the session check alone (any signed-in COE user) | ${noPermission.length} |`)
lines.push(`| … of those, routes that write (POST/PUT/PATCH/DELETE) | ${noPermission.filter((r) => r.writes).length} |`)
lines.push(`| Under a public prefix (must authenticate in the handler) | ${routes.length - protectedRoutes.length} |`)
lines.push(`| … of which show no recognised check in the handler | ${publicNoCheck.length} |`)
lines.push(`| Use the service-role client (RLS bypassed) | ${routes.filter((r) => r.serviceRole).length} |`)
lines.push('')
lines.push('**Reading the table.** *Access* is the gate in `proxy.ts`. *Authorised by* is what the handler itself checks; "—" on a session-gated route means any signed-in COE user may call it. *Inst.* marks handlers that take an institution id from the request — none of them compare it with the caller\'s own institution yet.')
lines.push('')

if (publicNoCheck.length) {
	lines.push('## Public-prefix routes with no recognised check')
	lines.push('')
	lines.push('Each of these is intentionally anonymous (sign-in, public forms) or needs review.')
	lines.push('')
	for (const r of publicNoCheck) lines.push(`- \`${r.route}\` — ${r.methods.join(', ')}`)
	lines.push('')
}

let area = ''
for (const r of routes) {
	const top = r.route.split('/')[2]
	if (top !== area) {
		area = top
		lines.push(`## /api/${area}`)
		lines.push('')
		lines.push('| Route | Methods | Access | Authorised by | Inst. |')
		lines.push('|---|---|---|---|:-:|')
	}
	lines.push(`| \`${r.route}\` | ${r.methods.join(', ') || '—'} | ${access(r)} | ${authorised(r)} | ${r.institution ? '●' : ''} |`)
	const next = routes[routes.indexOf(r) + 1]
	if (!next || next.route.split('/')[2] !== area) lines.push('')
}

fs.mkdirSync(path.dirname(OUT), { recursive: true })
fs.writeFileSync(OUT, lines.join('\n'))
console.log(`${routes.length} routes -> ${path.relative(ROOT, OUT)}`)
console.log(`session-gated: ${protectedRoutes.length} | with permission/role check: ${protectedRoutes.length - noPermission.length} | session only: ${noPermission.length} (writing: ${noPermission.filter((r) => r.writes).length})`)
console.log(`public prefix: ${routes.length - protectedRoutes.length} | no recognised check: ${publicNoCheck.length}`)
for (const r of publicNoCheck) console.log('   ', r.route, r.methods.join(','))
